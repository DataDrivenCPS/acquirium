"""Server lifecycle, quiescence, and event-log access shared by every run."""
from __future__ import annotations

import json
import shutil
import time
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import polars as pl

import acquirium as aq

ROOT = Path(__file__).resolve().parent
RUNS = ROOT / "runs"

SERVER_TOML = """# Generated by experiments/common.py; one private server per run.
[server]
enabled = true
data_dir = ".data"
timeseries_backend = "duckdb"
host = "127.0.0.1"
port = 0
workers = 1
recreate = false
exact_only = true
materialization_poll_seconds = {poll}
materialization_workers = {workers}
materialization_event_log = "events.jsonl"
"""


@dataclass
class Run:
    """One run directory with its own server, config, event log and results."""
    name: str
    poll_seconds: float = 0.25
    workers: int = 2
    directory: Path = field(init=False)
    client: Any = field(init=False, default=None)

    def __post_init__(self) -> None:
        stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S")
        self.directory = RUNS / self.name / stamp
        self.directory.mkdir(parents=True, exist_ok=True)

    @property
    def events_path(self) -> Path:
        return self.directory / "events.jsonl"

    def start(self) -> Any:
        """Start the private server and return the connected client."""
        (self.directory / "acquirium.toml").write_text(
            SERVER_TOML.format(poll=self.poll_seconds, workers=self.workers)
        )
        self.client = aq.init(config=self.directory / "acquirium.toml")
        return self.client

    def stop(self) -> None:
        aq.shutdown()
        self.client = None

    def restart(self) -> Any:
        """Stop the server and start it again on the same data directory."""
        self.stop()
        return self.start()

    def discard_data(self) -> None:
        """Delete the server's data so the run directory keeps only results."""
        shutil.rmtree(self.directory / ".data", ignore_errors=True)

    def save(self, name: str, value: Any) -> Path:
        """Write a result table or document into the run directory."""
        path = self.directory / name
        if isinstance(value, pl.DataFrame):
            value.write_parquet(path.with_suffix(".parquet"))
            value.write_csv(path.with_suffix(".csv"))
            return path.with_suffix(".parquet")
        path.write_text(json.dumps(value, indent=2, default=str))
        return path

    def events(self) -> pl.DataFrame:
        return read_events(self.events_path)


def read_events(path: Path) -> pl.DataFrame:
    """Load an event log as one frame; absent fields are null."""
    rows = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
    if not rows:
        return pl.DataFrame()
    return pl.from_dicts(rows, infer_schema_length=None)


def dag(client: Any) -> dict[str, Any]:
    return client.client.materialization_dag()


def wait_quiescent(client: Any, *, timeout: float = 600.0, settle: float = 1.0) -> float:
    """Block until the plan is current and every binding has consumed every revision.

    Returns the seconds waited. Raises on a failed binding or on timeout,
    since both would otherwise silently corrupt a measurement.
    """
    started = time.monotonic()
    deadline = started + timeout
    stable_since: float | None = None
    while time.monotonic() < deadline:
        status = client.graph_status()
        apps = client.list_apps()["apps"]
        graph = dag(client)
        # A deployment revokes the running generation; a binding caught mid-tick
        # records "binding is no longer active" and keeps that flag until it next
        # runs. It is a stale diagnostic, not a failed calculation.
        stale = lambda node: "binding is no longer active" in (node.get("error") or "")
        errors = {node["application_name"]: node["error"]
                  for node in graph["nodes"] if node.get("error") and not stale(node)}
        errors.update(graph.get("errors") or {})
        if errors:
            raise RuntimeError(f"materialization failed: {errors}")
        current = status.get("is_current", False) and all(app["plan_current"] for app in apps)
        idle = all(
            (node["status"] == "idle" or stale(node)) and node["consumed_revision"] is not None
            and node["consumed_revision"] >= node["current_revision"]
            for node in graph["nodes"]
        )
        if current and idle:
            if stable_since is None:
                stable_since = time.monotonic()
            elif time.monotonic() - stable_since >= settle:
                return time.monotonic() - started
        else:
            stable_since = None
        time.sleep(0.1)
    raise TimeoutError("materialization did not become quiescent in time")


def derived_nodes(client: Any) -> list[dict[str, Any]]:
    """Every compiled binding with its input and output stream identities."""
    return dag(client)["nodes"]


def fetch_stream(client: Any, ref_uri: str) -> pl.DataFrame:
    """A derived or raw stream as a ``time``/``value`` frame, sorted."""
    frame = client.client.timeseries_df(ref_uri)
    if frame.is_empty():
        return pl.DataFrame({"time": pl.Series([], dtype=pl.Datetime("us", "UTC")), "value": pl.Series([], dtype=pl.Float64)})
    frame = frame.rename({"ts": "time"}).select("time", "value").sort("time")
    return frame.with_columns(pl.col("time").cast(pl.Datetime("us", "UTC")))
